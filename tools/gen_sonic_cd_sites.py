#!/usr/bin/env python3
"""Verify complete retail instruction sequences and emit only CD hook sites.

The source contract retains independent Capstone M68000 instruction decoding
and existing disassembly annotation anchors. The generated header has only
addresses. Existing Megamix/IceCap/Launch Base/stack-return sites are retained.
"""
import argparse
import csv
import json
from pathlib import Path
import re
import zlib
ROOT = Path(__file__).resolve().parents[1]
BEGIN = '# BEGIN sonic cd hooks (generated by tools/gen_sonic_cd_sites.py)'
END = '# END sonic cd hooks'
MG = '# BEGIN megamix geometry hooks (generated by tools/gen_megamix_geometry_sites.py)'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--rom', type=Path, required=True)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    rom = args.rom.read_bytes()
    if len(rom) != 0x400000 or zlib.crc32(rom) != 0x63522553:
        raise ValueError('expected the supported S3K cartridge, CRC32 63522553')
    contract = json.loads((ROOT / 'tools/trilogy/data/sonic_cd_sites.json').read_text())
    with (ROOT / 'game/sonic3k/annotations_from_disasm.csv').open(newline='') as f:
        labels = {(int(r[0], 16), r[1]) for r in csv.reader(f) if r and re.fullmatch('[0-9A-Fa-f]{6}', r[0])}
    header = ['/* Generated by tools/gen_sonic_cd_sites.py; do not edit. */', '#pragma once']
    block = [BEGIN]
    for site in contract['sites']:
        address, code = site['address'], bytes.fromhex(site['code'])
        if tuple(site['anchor']) not in labels or rom[address:address + len(code)] != code:
            raise ValueError('unqualified CD hook: ' + site['name'])
        if sum(i['size'] for i in site['instructions']) != len(code):
            raise ValueError('incomplete instruction contract: ' + site['name'])
        header.append(f'#define TH_{site["name"]} 0x{address:06X}u')
        block += ['[[widescreen_site]]', f'addr = 0x{address:06X} # Sonic CD {site["name"]}', 'kind = "game_hook"']
    header.append('#define CD_GEOMETRY_CASES ' + ' '.join(f'case 0x{s["address"]:06X}u:' for s in contract['sites']))
    block.append(END)
    path = ROOT / 'game/sonic3k/game.toml'
    current = path.read_text()
    new = re.sub(r'\n' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '\n', current, flags=re.S)
    at = new.index(MG)
    new = new[:at].rstrip() + '\n\n' + '\n'.join(block) + '\n\n' + new[at:].lstrip()
    header = '\n'.join(header) + '\n'
    inc = ROOT / 'game/trilogy/scd_geometry_sites.h'
    if args.check:
        if not inc.exists() or inc.read_text() != header or current != new:
            raise ValueError('CD hook profile is stale; regenerate it')
    else:
        inc.write_text(header, newline='\n')
        path.write_text(new, newline='\n')
    print(f'Verified {len(contract["sites"])} CD hooks against full retail instructions and annotation anchors')


if __name__ == '__main__':
    main()
