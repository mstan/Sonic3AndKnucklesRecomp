       ('MONITOR_FIRE',0x1D954,'Monitor_Give_FireShield','52520229008e002b08e90000002b08e9'),
       ('MONITOR_LIGHTNING',0x1D992,'Monitor_Give_LightningShield','52520229008e002b08e90000002b08e9'),
       ('MONITOR_BUBBLE',0x1D9D0,'Monitor_Give_BubbleShield','52520229008e002b08e90000002b08e9'),
