#include "sonic3_sound_assets.h"
#include "sha256.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHECK(x) do { if(!(x)) { fprintf(stderr,"line %d: %s\n",__LINE__,#x);exit(1); } } while(0)
static uint8_t *read_file(const char *name,size_t *size)
{
    FILE *f=fopen(name,"rb");CHECK(f);CHECK(!fseek(f,0,SEEK_END));long n=ftell(f);CHECK(n>0);rewind(f);
    uint8_t *p=(uint8_t*)malloc((size_t)n);CHECK(p);CHECK(fread(p,1,(size_t)n,f)==(size_t)n);fclose(f);*size=(size_t)n;return p;
}
int main(int argc,char **argv)
{
    CHECK(argc==2 || argc==3);size_t size;uint8_t *rom=read_file(argv[1],&size);
    S3SoundSource source;char error[256];memset(&source,0xCC,sizeof source);
    CHECK(s3_sound_read_source(rom,size,&source,error,sizeof error));CHECK(!*error);
    if(argc==3){size_t zsize;uint8_t *z80=read_file(argv[2],&zsize);CHECK(zsize==0x2000);CHECK(!memcmp(source.z80,z80,zsize));free(z80);}
    else{
        /* Goldens independently reconstructed with the existing cartridge
         * Kosinski codec, not generated by this loader. No game bytes. */
        uint8_t digest[32];char hash[65];recompui_sha256_compute(source.z80,sizeof source.z80,digest);
        for(unsigned i=0;i<32;i++)snprintf(hash+2*i,3,"%02x",digest[i]);
        CHECK(!strcmp(hash,source.standalone_sonic3?"89cce5ac32ea71b9b5085c9174e72b3e61b19b72265d540d439a8deb5b55e7b9":"017154f759c21abaad985d055052d22fa2a60d5c606e0bfbda7c5ddffebfff81"));
    }
    unsigned songs=0,sounds=0;
    for(unsigned id=1;id<=source.music_count;id++){
        uint32_t p=s3_sound_music_source(&source,rom,id);if(!p)continue;
        CHECK(p<size-8);CHECK(rom[p+2]<=7 && rom[p+3]<=3);++songs;
    }
    for(unsigned id=0x33;id<=0xDB;id++){
        uint32_t p=s3_sound_sfx_source(&source,rom,id);CHECK(p && p<size-8);CHECK(rom[p+3]<=8);++sounds;
    }
    CHECK(!s3_sound_music_source(&source,rom,0) && !s3_sound_music_source(&source,rom,256));
    CHECK(!s3_sound_sfx_source(&source,rom,0) && !s3_sound_sfx_source(&source,rom,256));
    CHECK(songs>20 && sounds==169);
    S3SoundSource before=source;
    rom[123]^=1;CHECK(!s3_sound_read_source(rom,size,&source,error,sizeof error));CHECK(!memcmp(&source,&before,sizeof source));rom[123]^=1;
    CHECK(!s3_sound_read_source(rom,0,&source,error,sizeof error));CHECK(!s3_sound_read_source(NULL,size,&source,error,sizeof error));
    CHECK(!s3_sound_read_source(rom,size,(S3SoundSource*)rom,error,sizeof error));
    if(size==0x400000){
        uint8_t old=rom[0x2001F0];CHECK(old=='U');rom[0x2001F0]='J';
        CHECK(s3_sound_read_source(rom,size,&source,error,sizeof error));CHECK(!memcmp(&source,&before,sizeof source));CHECK(rom[0x2001F0]=='J');rom[0x2001F0]=old;
    }
    printf("PASS exact ROM-derived Z80 code/tables; %u available music and %u SFX headers; identity, bounds, immutable alias and Steam-header handling\n",songs,sounds);
    free(rom);return 0;
}
